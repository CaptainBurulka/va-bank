export const LINES = L;

/** Фраза за ключем «персонаж.подія.номер» з урахуванням налаштування: clean — без матів. null — невідомий ключ. */
export function lineText(key, clean = false) {
  if (typeof key !== 'string' || key.length > 40) return null;
  const [pid, ev, i] = key.split('.');
  const raw = L[pid]?.[ev]?.[Number(i)];
  if (typeof raw !== 'string') return null;
  return raw.replace(/\{([^|}]*)\|([^}]*)\}/g, (_, rude, mild) => (clean ? mild : rude));
}

/** Чи існує ключ фрази (для перевірки повідомлень у мережі). */
export const isLineKey = (key) => lineText(key) !== null;

/**
 * «Мішок» фраз без частих повторів: фраза не повторюється, доки не прозвучала більшість інших.
 * memory — об'єкт бота, що зберігається між подіями.
 */
export function pickLine(pid, ev, rng, memory) {
  const list = L[pid]?.[ev];
  if (!list?.length) return null;
  const key = `${pid}.${ev}`;
  memory.bags ||= {};
  let bag = memory.bags[key];
  if (!bag || !bag.length) {
    bag = list.map((_, i) => i);
    for (let i = bag.length - 1; i > 0; i--) { const j = Math.floor(rng() * (i + 1)); [bag[i], bag[j]] = [bag[j], bag[i]]; }
    // остання фраза попереднього мішка не йде першою
    if (memory.last?.[key] === bag[bag.length - 1] && bag.length > 1) [bag[0], bag[bag.length - 1]] = [bag[bag.length - 1], bag[0]];
    memory.bags[key] = bag;
  }
  const i = bag.pop();
  (memory.last ||= {})[key] = i;
  return `${pid}.${ev}.${i}`;
}

/**
 * Яку подію бот бачить у новому стані (порівняно з попереднім), з його погляду.
 * Повертає назву події або null. Пріоритет: ва-банк → підняття → джокер → блеф → перемога/програш.
 */
export function detectEvent(prev, view, me, weak = false) {
  if (!view || !prev) return null;
  // нові записи журналу з часу попереднього стану (журнал обрізається, тож шукаємо останній відомий запис)
  const last = prev.log.length ? JSON.stringify(prev.log[prev.log.length - 1]) : null;
  let from = 0;
  if (last) for (let i = view.log.length - 1; i >= 0; i--) if (JSON.stringify(view.log[i]) === last) { from = i + 1; break; }
  const fresh = view.log.slice(from);
  for (const e of fresh) if (e.t === 'raise' && e.allin) return 'allin';
  for (const e of fresh) if (e.t === 'raise' && e.p !== me && e.amount >= 10) return 'raise';
  if (view.phase === 'result' && prev.phase !== 'result' && view.result) {
    const r = view.result;
    if (r.jokers?.fired?.length) return 'joker';
    if (r.winner === me && r.reason === 'fold') return weak ? 'bluff' : 'win'; // суперник спасував на слабку руку — блеф
    if (r.reason === 'showdown' && (r.parts || []).includes(me)) return r.winner === me ? 'win' : r.winner === null ? null : 'lose';
  }
  return null;
}
